# logical operators in python are used to combine multiple boolean expressions and return a boolean values. 
# The three logical operators in python are and, or, and not.
"""
1.and operator : returns True if both values are True , otherwise it return False
2.or operator : returns True if at least one value is True , otherwise it return False
3.not operator : returns the opposite of the boolean value , if the value is True it will return False and if the value is False it will return True"""

print("True and True:", True and True)
print("True and False:", True and False)
print("False and True:", False and True)
print("False and False:" , False and False)


print("True or  True:", True or  True)
print("True or  False:", True or  False)
print("False or  True:", False or  True)
print("False or  False:" , False or  False) 


print("not True :" , not True)
print("not False :" , not False)
