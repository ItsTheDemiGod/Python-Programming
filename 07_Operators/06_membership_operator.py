# membership operator are used to check if a value is present in a collection or not
# we use in and not in for this purpose 

example_list = [1,2,3,4,5]

print(3 in example_list) # this will return True because 3 is present in the list
print(6 in example_list) # this will return False because 6 is not present in


print( 10 not in example_list) # this will return True because 10 is not present in the list
print( 2 not in example_list) # this will return False because 2 is present