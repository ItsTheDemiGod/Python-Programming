# Write a calculator that takes two numbers and an operator (+, -, *, /) from the user and prints the result.

a = int(input(" enter a number: "))
b = int(input(" enter a number: "))

print ("a + b =" , a+b) # addition 
print ("a - b =" , a-b) # substraction
print ("a * b =" , a*b) # multiplication
print ("a / b =" , a/b) # division , by default the division operator returns a float value 
print ("a % b =" , a%b) # modulo operator
print ("a ** b =" , a**b) # exponentiation operator
print ("a // b =" , a//b) # floor division 


