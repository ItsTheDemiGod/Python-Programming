# while loops in python executes a block of code as long as the condition remains true ,

i = 0
while i < 6: # this will remain true as long as i is less than 6 
    print(i)
    i+=1 # after each iteration we are incremeneting the value of 1 .



# workflow :
"first the condition is checked when the condition is true the block of code is executed also in  each iteration the value of i in increased by 1 and when 1 is printed i becomes 2 and the control goes back to while loop and again checked 2<6 is true so again code is executed and so it goes on"
